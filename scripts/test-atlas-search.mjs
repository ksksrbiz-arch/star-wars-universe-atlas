import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const base = process.env.ATLAS_URL || 'http://localhost:4173';
const evidenceDir = process.env.ATLAS_EVIDENCE_DIR || 'evidence/atlas-search';
await mkdir(evidenceDir, { recursive: true });
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
const checks = [];
try {
  for (const width of [1440, 390, 320]) {
    const page = await browser.newPage({ viewport: { width, height: 844 }, reducedMotion: 'reduce' });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/#galaxy');
    const trigger = page.getByRole('button', { name: 'Search the atlas', exact: true });
    const search = page.getByRole('combobox', { name: 'World, location, movie, episode or collection' });
    const open = async () => { await trigger.click(); await search.waitFor(); assert.equal(await search.evaluate(el => el === document.activeElement), true); };
    await open();
    await search.fill('Kassa');
    assert.equal(await page.getByRole('dialog').getByRole('option').count(), 1);
    assert.match(await page.getByRole('dialog').getByRole('option').innerText(), /Episode/i);
    await search.press('ArrowDown');
    const selectedId = await search.getAttribute('aria-activedescendant');
    assert(selectedId);
    assert.equal(await page.locator(`[id="${selectedId}"]`).getAttribute('aria-selected'), 'true');
    await search.press('Enter');
    await page.waitForURL(/#journey\/andor-s01e01$/);
    assert.equal(await page.getByRole('dialog').count(), 0);
    if (width < 721) await page.locator('.sheet-toggle').click();
    assert.equal(await page.locator('.journey-current h2').innerText(), 'Kassa');
    assert.equal(await page.locator('.journey-stop').count(), 0, 'Search must not reveal locations');
    await open(); await search.fill('Kassa'); await search.press('Enter');
    assert.equal(await page.locator('.journey-stop').count(), 0, 'Same-title selection keeps the reveal gate');
    await open(); await search.fill('Lothal');
    assert.match(await page.getByRole('dialog').getByRole('option').first().innerText(), /WORLD[\s\S]*Lothal[\s\S]*Mapped/);
    await search.press('ArrowDown'); await search.press('Enter');
    await page.waitForURL(/#galaxy\/lothal$/);
    assert.equal(await page.locator('.current-location strong').innerText(), 'Tatooine', 'Search selects; it does not jump');
    assert.match(await page.locator('.map-jump-bar').innerText(), /Lothal/);
    await open(); await search.fill('Rogue One');
    const rogueOptions = await page.getByRole('dialog').getByRole('option').allTextContents();
    assert(rogueOptions.some(text => /Movie/i.test(text)));
    assert(rogueOptions.some(text => /Collection/i.test(text)));
    await search.fill('Boba Fett');
    assert.equal(await page.getByRole('dialog').getByRole('option').count(), 8, 'Seven Boba Fett chapters and one collection');
    assert.match(await page.getByRole('dialog').getByRole('option').allTextContents().then(items => items.join(' ')), /Return of the Mandalorian/);
    await search.fill('Andor S01E02');
    assert.equal(await page.getByRole('dialog').getByRole('option').count(), 1);
    assert.match(await page.getByRole('dialog').getByRole('option').innerText(), /That Would Be Me/);
    await search.fill('Andor');
    assert.equal(await page.getByRole('dialog').getByRole('option').count(), 12);
    assert.match(await page.locator('.atlas-search-status').innerText(), /first 12 shown/);
    await search.press('ArrowUp');
    const lastResult = page.getByRole('dialog').getByRole('option').last();
    assert.equal(await lastResult.getAttribute('aria-selected'), 'true');
    assert(await page.locator('.atlas-search-results').evaluate(el => el.scrollTop > 0), 'Keyboard scrolls result list');
    await search.press('Tab');
    assert.equal(await page.getByRole('dialog').evaluate(el => el.contains(document.activeElement)), true, 'Native dialog contains keyboard focus');
    await search.focus();
    await search.fill('not-an-atlas-location-xyz'); assert.equal(await page.getByRole('dialog').getByRole('option').count(), 0);
    assert.match(await page.locator('.atlas-search-empty').innerText(), /No matches/);
    await search.fill('Peridea'); await search.press('Enter');
    assert.match(await page.locator('.atlas-search-inspection').innerText(), /No supported map placement/);
    assert.equal(await page.locator('.current-location strong').innerText(), 'Tatooine');
    assert.equal(await page.locator('.atlas-search-back').evaluate(el => el === document.activeElement), true);
    await page.locator('.atlas-search-back').click(); assert.equal(await search.inputValue(), 'Peridea');
    await search.fill('Ring of Kafrene'); await search.press('Enter');
    assert.equal(await page.getByRole('region', { name: 'Ring of Kafrene location details' }).count(), 1);
    assert.match(await page.locator('.location-dossier').innerText(), /Map position not established/);
    await page.locator('.atlas-search-back').click();
    await search.fill('Lothal');
    await page.screenshot({ path: `${evidenceDir}/search-${width}.png` });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    const dialogBounds = await page.getByRole('dialog').boundingBox();
    assert(dialogBounds.x >= 0 && dialogBounds.x + dialogBounds.width <= width, 'Dialog inside viewport');
    const pageScrollWidth = await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth);
    assert.equal(pageScrollWidth, true, 'Dialog has no horizontal overflow');
    await search.press('Escape');
    assert.equal(await trigger.evaluate(el => el === document.activeElement), true, 'Close restores focus');
    await open();
    assert.equal(await page.evaluate(() => document.documentElement.style.overflow), 'hidden');
    await page.mouse.click(1, 1);
    assert.equal(await page.getByRole('dialog').count(), 0, 'Backdrop click closes search');
    assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
    assert.notEqual(await page.evaluate(() => document.documentElement.style.overflow), 'hidden');
    await page.screenshot({ path: `${evidenceDir}/header-${width}.png` });
    assert.equal(await page.evaluate(() => localStorage.getItem('galactic-atlas.watch.v1')), null);
    assert.deepEqual(errors, []);
    checks.push({ width, keyboard: true, titleAndCollectionSearch: true, episodeCode: true, boundedResults: 12, unmappedIdentity: true, watchUnchanged: true });
    await page.close();
  }
  const travelPage = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await travelPage.goto(base + '/#galaxy/lothal');
  await travelPage.getByRole('button', { name: 'Explore Tatooine', exact: true }).waitFor();
  await travelPage.clock.install();
  await travelPage.clock.pauseAt(new Date());
  await travelPage.locator('.map-jump-bar button').evaluate(button => button.click());
  await travelPage.locator('.transit-panel').waitFor();
  // Trigger immediately: software WebGL plus auto-scrolling can exceed the two-second warp.
  await travelPage.getByRole('button', { name: 'Search the atlas', exact: true }).evaluate(button => button.click());
  assert.equal(await travelPage.locator('.transit-panel').count(), 0, 'Opening search cancels travel');
  const travelSearch = travelPage.getByRole('combobox', { name: 'World, location, movie, episode or collection' });
  await travelSearch.fill('Kassa'); await travelSearch.press('Enter');
  await travelPage.waitForURL(/#journey\/andor-s01e01$/);
  await travelPage.clock.runFor(2200);
  assert.equal(await travelPage.locator('.transit-panel').count(), 0);
  assert.equal(await travelPage.locator('.current-location strong').innerText(), 'Tatooine', 'Search navigation cancels pending warp without stale arrival');
  await travelPage.close();
  await writeFile(`${evidenceDir}/results.json`, JSON.stringify({ browser: 'Playwright Chromium software WebGL', checks }, null, 2));
  console.log('PASS global atlas search at1440/390/320: keyboard navigation, focus return, typed results, capped results, mapped preview without arrival, unplaced dossiers, episode-code lookup and unchanged spoiler/watch state.');
} finally { await browser.close(); }




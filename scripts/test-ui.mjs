import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir('evidence',{recursive:true});
const browser=await chromium.launch({args:['--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const checks=[];
const select=async name=>page.getByRole('button',{name:`Explore ${name}`,exact:true}).click();
const location=()=>page.locator('.current-location strong');
const waitLocation=async name=>{await page.waitForFunction(n=>document.querySelector('.current-location strong')?.textContent===n,name)};
await page.clock.install();
await page.goto((process.env.ATLAS_URL || 'http://localhost:4173') + "");
await page.locator('.galaxy-canvas canvas').waitFor();
await page.waitForTimeout(600);
assert.equal(await location().innerText(),'Tatooine');
await page.screenshot({path:'evidence/desktop.png',fullPage:true});
await select('Alderaan');
assert.equal(await location().innerText(),'Tatooine','preview must not change current location');
await page.getByRole('button',{name:'Jump to Alderaan',exact:true}).first().click();
await page.locator('.transit-panel').waitFor();
await page.waitForTimeout(350);
await page.screenshot({path:'evidence/warp.png'});
await waitLocation('Alderaan');
await page.locator('.transit-panel').waitFor({state:'detached'});
checks.push('Alderaan selection previews without arrival; animated warp arrives and clears transit');
await page.getByRole('button',{name:'Reset map view',exact:true}).click();
// Keep the two-second warp from finishing while browser automation schedules clicks.
await page.clock.pauseAt(await page.evaluate(() => Date.now() + 100));
await select('Yavin 4');
await page.getByRole('button',{name:'Jump to Yavin 4',exact:true}).first().click();
await page.getByRole('button',{name:'Cancel',exact:true}).click();
assert.equal(await location().innerText(),'Alderaan');checks.push('Cancel preserves departure world');
await select('Yavin 4');
await page.getByRole('button',{name:'Jump to Yavin 4',exact:true}).first().click();
await page.getByRole('button',{name:'Skip animation'}).click();
await waitLocation('Yavin 4');checks.push('Skip immediately arrives at selected destination');
await page.getByRole('button',{name:'Return to previous world',exact:true}).click();
await waitLocation('Alderaan');checks.push('Back restores prior destination');
await page.clock.resume();
await page.getByRole('switch',{name:'Reduce motion'}).click();
await page.getByRole('button',{name:'Reset map view',exact:true}).click();
await select('Tatooine');
await page.getByRole('button',{name:'Jump to Tatooine',exact:true}).first().click();
await waitLocation('Tatooine');assert.equal(await page.locator('.transit-panel').count(),0);checks.push('Reduced motion arrives without warp');
await page.getByRole('button',{name:'Reset map view',exact:true}).click();
const canvas=await page.locator('.galaxy-canvas canvas').boundingBox();
const before=await page.getByRole('button',{name:'Explore Alderaan',exact:true}).boundingBox();
await page.mouse.move(canvas.x+canvas.width*.25,canvas.y+canvas.height*.6);await page.mouse.down();await page.mouse.move(canvas.x+canvas.width*.25+75,canvas.y+canvas.height*.6+25,{steps:8});await page.mouse.up();await page.waitForTimeout(400);
const after=await page.getByRole('button',{name:'Explore Alderaan',exact:true}).boundingBox();
assert.ok(Math.abs(before.x-after.x)>20,'pan must move anchored marker');checks.push('Pointer pan moves map markers');
await page.getByRole('button',{name:'Reset map view',exact:true}).click();
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(400);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);checks.push('390px mobile layout has no horizontal overflow');
await page.screenshot({path:'evidence/mobile.png',fullPage:true});
await page.setViewportSize({width:320,height:740});await page.waitForTimeout(200);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);checks.push('320px layout has no horizontal overflow');
assert.deepEqual(errors,[]);checks.push('No browser page errors');
await writeFile('evidence/test-results.json',JSON.stringify({date:'2026-11-07',environment:'Playwright Chromium; software WebGL; desktop and resized mobile viewports, not physical-device performance evidence',checks,errors},null,2));
console.log(JSON.stringify({checks,errors},null,2));await browser.close();

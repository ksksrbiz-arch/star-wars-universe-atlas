import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base = process.env.ATLAS_URL || 'http://localhost:4173';
const browser = await chromium.launch({args:['--enable-unsafe-swiftshader']});
const context = await browser.newContext({viewport:{width:390,height:844}});
const page = await context.newPage();
const errors = [];
context.on('page', tab => tab.on('pageerror', error => errors.push(error.message)));
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${base}/#library`);
  await page.locator('.collection-tabs').getByRole('button',{name:/Andor/}).click();
  const search = page.getByRole('textbox',{name:'Search films and episodes'});
  for (const query of ['S1E2','s01e02','season 1 episode 2']) {
    await search.fill(query);
    await page.waitForFunction(() => document.querySelectorAll('.catalog-item').length === 1);
    assert.equal(await page.locator('.catalog-item h2').innerText(),'That Would Be Me');
  }
  await page.locator('.collection-tabs').getByRole('button',{name:/The Clone Wars/}).click();
  await search.fill('S1E2');
  await page.waitForFunction(() => document.querySelectorAll('.catalog-item').length === 1);
  assert.equal(await page.locator('.catalog-item h2').innerText(),'Rising Malevolence');
  await page.locator('.collection-tabs').getByRole('button',{name:/Andor/}).click();
  console.log('PASS: library searches by compact, padded, and full episode numbers');
  await search.fill('S1E1');
  const other = await context.newPage();
  await other.goto(`${base}/#library`);
  await page.locator('.watched-button').click();
  await other.waitForFunction(() => document.querySelector('.library-footer')?.textContent.includes('1 watched'));
  await other.getByRole('button',{name:'Mark watched: A New Hope',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('.library-footer')?.textContent.includes('2 watched'));
  await page.reload();
  assert.match(await page.locator('.library-footer').innerText(),/2 watched/);
  await other.evaluate(() => localStorage.clear());
  await page.waitForFunction(() => document.querySelector('.library-footer')?.textContent.includes('0 watched'));
  console.log('PASS: cross-tab progress synchronizes, retains both edits on reload, and handles clear');
  await page.goto(`${base}/#galaxy`);
  await page.getByRole('button',{name:'Reveal linked unwatched titles'}).click();
  assert.equal(await page.locator('.world-stories .world-story-grid a').count(),6);
  const total = Number(await page.locator('.world-stories h3 span').innerText());
  assert.ok(total > 6);
  await page.getByRole('button',{name:/Show .* more linked stories/}).click();
  assert.equal(await page.locator('.world-stories .world-story-grid a').count(),total);
  const lastLink = page.locator('.world-stories .world-story-grid a').last();
  const href = await lastLink.getAttribute('href');
  await lastLink.click();
  await page.locator('.journey-current h2').waitFor();
  assert.equal(new URL(page.url()).hash,href);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
  console.log('PASS: all world-linked titles can be expanded and opened on mobile');
  const blocked = await browser.newContext();
  await blocked.addInitScript(() => { Storage.prototype.setItem = () => { throw new DOMException('Quota exceeded','QuotaExceededError'); }; });
  const blockedPage = await blocked.newPage();
  await blockedPage.goto(`${base}/#library`);
  await blockedPage.getByRole('button',{name:'Mark watched: A New Hope',exact:true}).click();
  await blockedPage.getByRole('button',{name:'Mark watched: The Empire Strikes Back',exact:true}).click();
  assert.match(await blockedPage.locator('.library-footer').innerText(),/2 watched/);
  assert.match(await blockedPage.locator('.storage-warning').innerText(),/could not save/);
  await blocked.close();
  const denied = await browser.newContext();
  await denied.addInitScript(() => { Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Denied','SecurityError');}}); });
  const deniedPage = await denied.newPage();
  deniedPage.on('pageerror',error => errors.push(error.message));
  await deniedPage.goto(`${base}/#library`);
  await deniedPage.getByRole('button',{name:'Mark watched: A New Hope',exact:true}).click();
  await deniedPage.evaluate(() => window.dispatchEvent(new StorageEvent('storage',{key:'galactic-atlas.watch.v1'})));
  assert.match(await deniedPage.locator('.library-footer').innerText(),/1 watched/);
  await denied.close();
  console.log('PASS: quota failure and denied storage retain in-memory progress without errors');
  assert.deepEqual(errors,[]);
} finally { await browser.close(); }

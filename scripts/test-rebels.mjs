import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { REBELS_CONNECTIONS } from '../src/connectionsRebels.ts';
import { STORY_SEQUENCES } from '../src/chronology.ts';
import { getLocationKind } from '../src/locations.ts';
const catalog=JSON.parse(readFileSync('src/catalog.generated.json','utf8'));
const source=JSON.parse(readFileSync('docs/rebels-season-1-source.json','utf8'));
const items=catalog.items.filter(x=>x.seriesId==='rebels'&&x.season===1);
assert.equal(items.length,14);
assert.deepEqual(items.flatMap(x=>Array.from({length:(x.episodeEnd??x.episode)-x.episode+1},(_,i)=>x.episode+i)),Array.from({length:15},(_,i)=>i+1));
assert.equal(items[0].releaseDate,'2014-10-03');assert.equal(items[0].episodeEnd,2);
assert(!items.some(x=>x.id==='rebels-s01e02'));
assert(items.every(x=>x.runtimeMinutes===null));
assert.deepEqual(STORY_SEQUENCES.find(x=>x.id==='rebels').itemIds.slice(0,14),items.map(x=>x.id));
assert.equal(source.episodeEvidence.length,14);
for(const e of source.episodes.slice(1))assert.equal(e.number,e.providerNumber+2);
assert.equal(catalog.metadata.sourceFiles.find(x=>x.name==='rebels-season-1-source.json').sha256,createHash('sha256').update(readFileSync('docs/rebels-season-1-source.json')).digest('hex'));
assert.equal(REBELS_CONNECTIONS.length,20);assert.equal(new Set(REBELS_CONNECTIONS.map(x=>x.itemId)).size,14);
assert(REBELS_CONNECTIONS.every(x=>x.sourceUrl.startsWith('https://www.starwars.com/')&&!('x' in x)&&!('sequence' in x)));
assert(!REBELS_CONNECTIONS.some(x=>['anaxes','lasan','kashyyyk','dagobah','coruscant'].includes(x.worldId)));
assert(!REBELS_CONNECTIONS.some(x=>x.itemId==='rebels-s01e14'&&x.worldId==='mustafar'));
assert.equal(REBELS_CONNECTIONS.find(x=>x.worldId==='mustafar').context,'orbit');
assert.equal(getLocationKind('fort-anaxes'),'asteroid-outpost');
for(const id of ['merchant-one','sovereign'])assert.equal(getLocationKind(id),'ship');
console.log('Rebels passed: 14 watch records / 15 official parts / 20 sourced associations; ships, asteroid and orbit distinctions preserved.');
